"""M1 proof: detect real programs on this machine and compare with what each is known to be built with.

  py -3 tools/prove_m1.py [--launch]      --launch also starts (through CIG's safe launcher) the listed programs that
                                          are not running, detects them, and closes them gracefully afterwards.
Writes docs/proofs/M1-detection.md and appends the observations to the library entries ("observed", source probe).
"""
import datetime
import json
import os
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from cig import detect, launch  # noqa: E402

# (exe, expected framework, why we know, launch path or None = only if already running)
CASES = [
    ("ModOrganizer.exe", "qt6", "MO2 2.5 is built on Qt 6", None),
    (r"C:\Program Files\EqualizerAPO\Editor.exe", "qt6", "Qt6Core.dll ships beside it", "launch"),
    (r"C:\Program Files\IDA Freeware 8.4\ida64.exe", "qt5", "Qt5Core.dll ships beside it", "launch"),
    ("Discord.exe", "electron", "Discord is an Electron app", None),
    ("claude.exe", "electron", "the Claude desktop app is Electron", None),
    ("Spotify.exe", "chromium", "Spotify desktop is CEF", None),
    ("chrome.exe", "chromium", "Google Chrome", None),
    (r"C:\Program Files\7-Zip\7zFM.exe", "win32", "7-Zip File Manager: Win32 common controls", "launch"),
    ("notepad.exe", "winui3", "Windows 11 Notepad depends on the Windows App Runtime (WinUI 3)", "launch"),
    ("mspaint.exe", "winui3", "Windows 11 Paint depends on the Windows App Runtime (WinUI 3)", "launch"),
    ("SystemSettings.exe", "uwp", "Windows Settings is a UWP CoreWindow app", None),
    ("LibreHardwareMonitor.exe", "winforms", "LibreHardwareMonitor is .NET WinForms", None),
    ("powershell.exe", "console", "Windows PowerShell is a console program", None),
]


def main(do_launch: bool):
    rows, launched = [], []
    for exe, want, why, how in CASES:
        name = os.path.basename(exe)
        pids = detect.resolve_pids(name)
        pids = [p for p in pids if detect.windows_of(p)]
        if not pids and do_launch and how == "launch":
            r = launch.launch(exe, [])
            if r.get("ok"):
                launched.append(r["pid"])
                time.sleep(2.0)
                pids = [r["pid"]]
            else:
                rows.append((name, want, "not run", "-", "-", f"launch refused/failed: {r.get('reason')}", why))
                continue
        if not pids:
            rows.append((name, want, "not running", "-", "-", "-", why))
            continue
        t0 = time.time()
        d = detect.detect(pids[0])
        dt = time.time() - t0
        got = d.get("framework")
        uia = d["process"]["uia"]
        rows.append((name, want, got, d.get("framework_version") or "-",
                     ", ".join(f"{a['name']} {a['score']}" for a in d["adapters"][:3]),
                     f"uia {uia.get('top_framework_id')} rich {uia.get('score')} | {dt:.1f}s"
                     + (f" | hybrid {d['hybrid_with']}" if d.get("hybrid_with") else "")
                     + (f" | integrity {d['process']['integrity']}" if d['process']['integrity'] != "medium" else ""),
                     why))
        observe(d)
    for pid in launched:
        launch.close(pid)
    write(rows)
    ok = sum(1 for r in rows if r[1] == r[2])
    tried = sum(1 for r in rows if r[2] not in ("not running", "not run"))
    print(f"{ok}/{tried} correct ({len(rows)} cases)")
    return ok, tried


def observe(d):
    fw = d.get("framework")
    p = REPO / "library" / "frameworks" / f"{fw}.json"
    if not p.exists():
        return
    e = json.loads(p.read_text(encoding="utf-8"))
    obs = e.setdefault("observed", [])
    rec = {"app": d["process"]["name"], "version": d["process"].get("version"),
           "framework_version": d.get("framework_version"), "date": datetime.date.today().isoformat(),
           "uia_framework_ids": sorted((d["process"]["uia"].get("framework_ids") or {}).keys()),
           "window_classes": d["process"]["window_classes"][:6], "richness": d["process"]["uia"].get("score")}
    obs[:] = [o for o in obs if o.get("app") != rec["app"]] + [rec]
    tag = f"probe:{rec['date']} detection of installed apps (tools/prove_m1.py)"
    if tag not in e["source"]:
        e["source"] = [s for s in e["source"] if not s.startswith("probe:") or "prove_m1" not in s] + [tag]
    p.write_text(json.dumps(e, indent=1), encoding="utf-8")


def write(rows):
    out = REPO / "docs" / "proofs" / "M1-detection.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# M1 proof - framework detection on installed programs ({datetime.datetime.now():%Y-%m-%d %H:%M})", "",
             "Generated by `tools/prove_m1.py`. Expected = what the program is known to be built with (last column).", "",
             "| Program | Expected | Detected | Framework version | Top adapters | UIA / time / notes | Why expected |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        mark = "" if r[2] in ("not running", "not run") else (" OK" if r[1] == r[2] else " **WRONG**")
        lines.append(f"| {r[0]} | {r[1]} | {r[2]}{mark} | {r[3]} | {r[4]} | {r[5]} | {r[6]} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    ok, tried = main("--launch" in sys.argv)
    sys.exit(0 if ok == tried and tried >= 10 else 1)
